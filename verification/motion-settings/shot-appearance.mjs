import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 820 } });
await page.goto('http://127.0.0.1:4173');
await page.getByRole('button', { name: 'Settings', exact: true }).click();
await page.getByRole('radio', { name: 'Reduce', exact: true }).click();
await page.locator('section[aria-label="Appearance"]').scrollIntoViewIfNeeded();
await page.waitForTimeout(120);
await page.screenshot({ path: 'verification/motion-settings/05-appearance-reduce.png' });
await page.getByRole('radio', { name: 'System', exact: true }).click();
await page.waitForTimeout(80);
await page.screenshot({ path: 'verification/motion-settings/06-appearance-system.png' });
await browser.close();
